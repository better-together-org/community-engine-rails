#!/usr/bin/env ruby
# frozen_string_literal: true

# Generates db/community-engine-db.dbml from spec/dummy/db/schema.rb, the dumped schema of the engine.
# It reads the schema file with a small recorder instead of connecting to a database, so the output is
# deterministic and needs no Rails boot. Run through bin/export_schema_diagrams.
#
#   ruby scripts/export_schema_dbml.rb [--schema PATH] [--output PATH]

require 'json'
require 'optparse'
require 'pathname'

# Collects what ActiveRecord::Schema.define would send to the connection.
class SchemaRecorder
  Column = Struct.new(:name, :type, :null, :default, :limit, :array)
  Table = Struct.new(:name, :primary_key, :columns, :indexes)
  Index = Struct.new(:columns, :name, :unique)
  Reference = Struct.new(:from_table, :to_table, :column, :primary_key, :name)

  attr_reader :tables, :references, :extensions, :version

  def initialize
    @tables = []
    @references = []
    @extensions = []
  end

  def define(version:, &)
    @version = version
    instance_eval(&)
  end

  def enable_extension(name)
    @extensions << name
  end

  def create_table(name, id: :bigserial, **_options)
    table = Table.new(name, id, [], [])
    table.columns << Column.new('id', pk_type(id), false, nil, nil, false) unless id == false
    yield TableRecorder.new(table)
    @tables << table
  end

  def add_foreign_key(from, to, column: nil, primary_key: 'id', name: nil, **_options)
    @references << Reference.new(from, to, column || "#{singular(to.to_s)}_id", primary_key, name)
  end

  # Anything else in schema.rb (comments, check constraints, views) does not change the diagram.
  def method_missing(_name, *_args, **_kwargs, &_block)
    nil
  end

  def respond_to_missing?(*)
    true
  end

  private

  # schema.rb omits `column:` when it follows the Rails convention (singular table name + _id).
  def singular(name)
    return "#{name.delete_suffix('ies')}y" if name.end_with?('ies')

    name.delete_suffix('s')
  end

  def pk_type(id)
    id == :uuid ? 'uuid' : id.to_s
  end

  # Receives the `t.<type> "name", options` calls inside a create_table block.
  class TableRecorder
    def initialize(table)
      @table = table
    end

    def index(columns, name: nil, unique: false, **_options)
      @table.indexes << Index.new(Array(columns), name, unique)
    end

    def method_missing(type, name = nil, **options, &_block)
      return super unless name.is_a?(String)

      @table.columns << Column.new(name, type.to_s, options.fetch(:null, true), options[:default], options[:limit],
                                   options.fetch(:array, false))
    end

    def respond_to_missing?(_name, _include_private = false)
      true
    end
  end
end

# Turns recorded tables into DBML.
class DbmlWriter
  TYPE_MAP = { 'string' => 'varchar', 'datetime' => 'timestamp' }.freeze

  def initialize(recorder)
    @recorder = recorder
  end

  def to_s
    parts = [header]
    @recorder.tables.sort_by(&:name).each { |table| parts << table_block(table) }
    @recorder.references.sort_by { |ref| [ref.from_table, ref.column, ref.to_table] }.each do |ref|
      parts << reference_line(ref)
    end
    "#{parts.join("\n\n")}\n"
  end

  private

  def header
    <<~TEXT.chomp
      // Generated by scripts/export_schema_dbml.rb from spec/dummy/db/schema.rb (version #{@recorder.version}).
      // Do not hand-edit; run bin/export_schema_diagrams after changing a migration.
      // Extensions: #{@recorder.extensions.sort.join(', ')}
    TEXT
  end

  def table_block(table)
    lines = table.columns.map { |column| "  #{column_line(table, column)}" }
    index_lines = table.indexes.map { |index| "    #{index_line(index)}" }
    lines += ['', '  indexes {', *index_lines, '  }'] if index_lines.any?
    "Table #{quote(table.name)} {\n#{lines.join("\n")}\n}"
  end

  def column_line(table, column)
    settings = []
    settings << 'pk' if column.name == 'id' && table.primary_key != false
    settings << 'not null' if column.null == false && !settings.include?('pk')
    settings << "default: #{default_literal(column.default)}" unless column.default.nil?
    type = TYPE_MAP.fetch(column.type, column.type)
    type = "#{type}[]" if column.array
    type = "#{type}(#{column.limit})" if column.limit && type == 'varchar'
    "#{quote(column.name)} #{type}#{settings.empty? ? '' : " [#{settings.join(', ')}]"}"
  end

  def index_line(index)
    columns = index.columns
    target = columns.one? ? quote(columns.first) : "(#{columns.map { |c| quote(c) }.join(', ')})"
    settings = []
    settings << 'unique' if index.unique
    settings << "name: #{quote(index.name)}" if index.name
    "#{target}#{settings.empty? ? '' : " [#{settings.join(', ')}]"}"
  end

  def reference_line(ref)
    "Ref: #{quote(ref.from_table)}.#{quote(ref.column)} > #{quote(ref.to_table)}.#{quote(ref.primary_key)}"
  end

  # `default: -> { "gen_random_uuid()" }` is a Proc in schema.rb; show it as a DBML expression.
  def default_literal(default)
    return "`#{default.call}`" if default.respond_to?(:call)
    return "'#{default}'" if default.is_a?(String)
    return "'{#{default.join(',')}}'" if default.is_a?(Array)
    return "'#{default.to_json}'" if default.is_a?(Hash)

    default.to_s
  end

  def quote(name)
    %("#{name}")
  end
end

options = { schema: 'spec/dummy/db/schema.rb', output: 'db/community-engine-db.dbml' }
OptionParser.new do |parser|
  parser.on('--schema PATH') { |value| options[:schema] = value }
  parser.on('--output PATH') { |value| options[:output] = value }
end.parse!

recorder = SchemaRecorder.new
schema_source = File.read(options[:schema])
# schema.rb opens with `ActiveRecord::Schema[7.2].define(...)`; point it at the recorder.
module ActiveRecord
  # Stand-in so the schema file can be evaluated without Rails.
  module Schema
    def self.[](_version)
      Thread.current[:schema_recorder]
    end
  end
end
Thread.current[:schema_recorder] = recorder
TOPLEVEL_BINDING.eval(schema_source, options[:schema])

output = Pathname.new(options[:output])
output.dirname.mkpath
output.write(DbmlWriter.new(recorder).to_s)
puts "Wrote #{options[:output]} (#{recorder.tables.size} tables, #{recorder.references.size} foreign keys)"
