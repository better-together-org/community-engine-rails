module BetterTogether
  module AccessContract
    # Renders the contract and snapshot into Markdown pages and Mermaid sources.
    # `files` returns { relative_path => content }; the rake task writes or checks them.
    class DocsGenerator
      HEAT_ACTIONS = %w[show scope].freeze
      TREE_DEFAULT_ACTION = 'show'

      attr_reader :contract, :drift

      def initialize(contract = Contract.load, snapshot = Snapshot.load)
        @contract = contract
        @drift = Drift.new(contract, snapshot)
        @actual = Snapshot.flatten(snapshot)
        @inventory = Inventory.new(contract)
        @invariants = Invariants.new(contract, snapshot)
      end

      def files
        out = { "#{DOCS_DIR}/README.md" => index_page, "#{DOCS_DIR}/open_decisions.md" => decisions_page,
                "#{DOCS_DIR}/role_permission_matrix.md" => permission_page }
        contract.subsystems.each_key { |name| out["#{DOCS_DIR}/#{name}.md"] = subsystem_page(name) }
        out.merge(diagram_sources)
      end

      def diagram_sources
        trees = contract.resources.to_h { |key, res| ["#{DIAGRAM_SOURCE_DIR}/#{tree_name(key)}.mmd", tree_source(key, res)] }
        trees.merge("#{DIAGRAM_SOURCE_DIR}/access_contract_heatmap_intended.mmd" => heatmap_source(:intended),
                    "#{DIAGRAM_SOURCE_DIR}/access_contract_heatmap_actual.mmd" => heatmap_source(:actual))
      end

      def write
        files.each do |path, content|
          full = AccessContract.root.join(path)
          FileUtils.mkdir_p(full.dirname)
          File.write(full, content)
        end
      end

      # Paths whose committed content differs from what would be generated.
      def stale
        files.reject { |path, content| File.exist?(AccessContract.root.join(path)) && File.read(AccessContract.root.join(path)) == content }.keys
      end

      def counts
        {
          'subsystems' => contract.subsystems.size, 'resources' => contract.resources.size,
          'personas' => contract.personas.size, 'cells' => contract.cells.size,
          'known_deviations' => drift.known_deviations.size, 'undecided' => drift.undecided.size
        }
      end

      private

      def tree_name(resource)
        "access_contract_#{resource}_decision_tree"
      end

      # ---------------------------------------------------------------- pages

      def index_page
        <<~MD
          # Access contracts (pilot)

          Generated by `rake better_together:access:docs`. Do not edit by hand. How to change an entry: [How to add or change an access contract entry](../../developers/access_contracts.md).

          An access contract records what access we decided each persona should have to each record, in `config/access_contracts/*.yml`. A probe spec records what the policies actually do in `spec/access_contract/snapshot.json`. CI fails when the two differ, unless the difference is a recorded known deviation or an open decision.

          ## Pilot size

          #{count_table}

          ## Persona by classification heatmaps

          Each cell summarizes the show and scope checks of every pilot resource with that classification. `allow` means every cell allows, `deny` means every cell denies, `mixed` means it depends on the resource, state or action.

          ### Intended (the contract)

          #{diagram_link('access_contract_heatmap_intended', 'Intended access heatmap')}

          #{heatmap_table(:intended)}

          ### Actual (the probe snapshot)

          #{diagram_link('access_contract_heatmap_actual', 'Actual access heatmap')}

          #{heatmap_table(:actual)}

          ## Pages

          - [Communities](communities.md)
          - [People](people.md)
          - [Role by permission matrix](role_permission_matrix.md)
          - [Open decisions](open_decisions.md)

          ## Invariants checked in CI

          #{invariant_list}

          ## Personas

          #{persona_table}

          ## Classifications

          #{classification_table}
        MD
      end

      def count_table
        rows = counts.map { |k, v| "| #{k.tr('_', ' ')} | #{v} |" }
        (['| Measure | Count |', '| --- | --- |'] + rows).join("\n")
      end

      def invariant_list
        @invariants.all.keys.map { |name| "- #{name.capitalize}" }.join("\n")
      end

      def persona_table
        rows = contract.personas.map { |k, v| "| `#{k}` | #{v['status']} | #{v['description']} |" }
        (['| Persona | Status | Meaning |', '| --- | --- | --- |'] + rows).join("\n")
      end

      def classification_table
        rows = contract.classifications.map do |k, v|
          "| `#{k}` | #{v['standing_role_may_read'] ? 'yes' : 'no'} | #{v['description']} |"
        end
        (['| Classification | Standing roles may read | Meaning |', '| --- | --- | --- |'] + rows).join("\n")
      end

      def diagram_link(name, alt)
        "![#{alt}](../../diagrams/exports/png/#{name}.png)\n\n[Open the SVG](../../diagrams/exports/svg/#{name}.svg) · [Mermaid source](../../diagrams/source/#{name}.mmd)"
      end

      # ----------------------------------------------------------- subsystem

      def subsystem_page(name)
        file = contract.subsystems.fetch(name)
        parts = ["# #{file['title']} access contract", '', file['summary'], '', 'Generated by `rake better_together:access:docs`.', '',
                 '## Inventory', '', inventory_table(name), '', '### Routed actions', '', routes_table(file), '',
                 '### Policies not contracted yet', '', deferred_table(file)]
        contract.resources.select { |_, r| r['subsystem'] == name }.each { |key, res| parts.push('', resource_section(key, res)) }
        "#{parts.join("\n")}\n"
      end

      def inventory_table(name)
        header = ['| Resource | Model | Policy | Classification | Views | MCP tools | Jobs |', '| --- | --- | --- | --- | --- | --- | --- |']
        rows = contract.resources.select { |_, r| r['subsystem'] == name }.map { |key, res| inventory_row(key, res) }
        (header + rows).join("\n")
      end

      def inventory_row(key, res)
        views = (res['controllers'] || []).flat_map { |c| @inventory.views_for(c) }.uniq.size
        mcp = @inventory.mcp_tools(res['model']).map { |f| File.basename(f, '.rb') }
        jobs = @inventory.jobs(res['model']).map { |f| File.basename(f, '.rb') }
        "| [#{res['title']}](##{anchor(res['title'])}) (`#{key}`) | `#{res['model']}` | `#{res['policy']}` | `#{res['classification']}` | " \
          "#{views} files | #{list_or_none(mcp)} | #{list_or_none(jobs)} |"
      end

      def list_or_none(items)
        items.empty? ? 'none' : items.map { |i| "`#{i}`" }.join(', ')
      end

      def anchor(title)
        title.downcase.gsub(/[^a-z0-9 -]/, '').tr(' ', '-')
      end

      def routes_table(file)
        routes = @inventory.routed_actions(file['controllers'] || [])
        header = ['| Controller action | Verb | Example path | Authorization check |', '| --- | --- | --- | --- |']
        rows = routes.map do |r|
          "| `#{r[:controller].delete_prefix('better_together/')}##{r[:action]}` | #{r[:verb]} | `#{r[:path]}` | #{route_status(r)} |"
        end
        (header + rows).join("\n")
      end

      def route_status(route)
        detail = route[:detail] ? " (#{route[:detail]})" : ''
        "#{route[:status].to_s.tr('_', ' ')}#{detail}"
      end

      def deferred_table(file)
        deferred = file['deferred_policies'] || {}
        return 'None.' if deferred.empty?

        (['| Policy | Reason |', '| --- | --- |'] + deferred.map { |k, v| "| `#{k}Policy` | #{v} |" }).join("\n")
      end

      # ------------------------------------------------------------ resource

      def resource_section(key, res)
        parts = ["## #{res['title']}", '', "`#{res['model']}` · policy `#{res['policy']}` · classification `#{res['classification']}`", '',
                 '### Decision tree', '', "Decision tree for #{tree_action(res)}. Dashed red nodes are rules the app applies that the privacy rule does not intend.", '',
                 diagram_link(tree_name(key), "#{res['title']} decision tree"), '', '### Rules in order', '', rules_table(res)]
        res['actions'].each_key { |action| parts.push('', action_section(key, res, action)) }
        parts.join("\n")
      end

      def tree_action(res)
        res['tree_action'] || TREE_DEFAULT_ACTION
      end

      def rules_table(res)
        header = ['| # | Rule | Question | Decides | Note |', '| --- | --- | --- | --- | --- |']
        rows = res['rules'].each_with_index.map do |rule, i|
          flag = rule['intended'] == false ? 'not intended' : rule['on_yes']
          "| #{i + 1} | `#{rule['id']}` | #{rule['question']} | #{flag} | #{rule['note']} |"
        end
        (header + rows).join("\n")
      end

      def action_section(key, res, action)
        states = contract.action_states(key, action)
        footnotes = []
        header = ["| Persona | #{states.join(' | ')} |", "| --- | #{states.map { '---' }.join(' | ')} |"]
        rows = contract.personas.keys.map { |persona| matrix_row(key, action, persona, states, footnotes) }
        parts = ["### #{action}", '', (header + rows).join("\n")]
        parts.push('', footnote_block(footnotes)) if footnotes.any?
        parts.push('', reasons_block(key, action, res))
        parts.join("\n")
      end

      def matrix_row(key, action, persona, states, footnotes)
        label = contract.personas[persona]['status'] == 'pending' ? "`#{persona}` (pending)" : "`#{persona}`"
        cells = states.map do |state|
          cell = contract.cell(key, action, persona, state)
          cell ? cell_text(cell, footnotes) : 'pending'
        end
        "| #{label} | #{cells.join(' | ')} |"
      end

      def cell_text(cell, footnotes)
        case cell.outcome
        when 'na' then 'n/a'
        when 'conditional' then "conditional #{note(footnotes, "#{cell.condition} Probe fixture: #{cell.fixture}.")} <sub>#{cell.rule}</sub>"
        when 'undecided' then "undecided (app: #{cell.undecided['actual']}) #{note(footnotes, decision_note(cell.undecided['decision']))}"
        else plain_text(cell, footnotes)
        end
      end

      def plain_text(cell, footnotes)
        return "#{cell.outcome} <sub>#{cell.rule}</sub>" unless cell.deviation

        "#{cell.outcome} (app: #{cell.deviation['actual']}) #{note(footnotes, decision_note(cell.deviation['decision']))}"
      end

      def decision_note(id)
        d = contract.decisions.fetch(id)
        "#{id}, #{d['kind'].tr('_', ' ')}: #{d['title']}."
      end

      def note(footnotes, text)
        footnotes << text unless footnotes.include?(text)
        "[^#{footnotes.index(text) + 1}]"
      end

      def footnote_block(footnotes)
        footnotes.each_with_index.map { |t, i| "[^#{i + 1}]: #{t}" }.join("\n")
      end

      def reasons_block(key, action, _res)
        groups = contract.cells.values.select { |c| c.resource == key && c.action == action && c.reason }
                         .group_by { |c| [c.outcome, c.rule, c.reason] }.sort_by { |k, _| k.map(&:to_s) }
        lines = groups.map do |(outcome, rule, reason), cells|
          personas = cells.map(&:persona).uniq.sort.join(', ')
          "- #{outcome} via `#{rule}`: #{reason} (#{personas})"
        end
        "<details><summary>Reasons</summary>\n\n#{lines.join("\n")}\n\n</details>"
      end

      # ----------------------------------------------------- open decisions

      def decisions_page
        parts = ['# Open access decisions', '',
                 'Generated by `rake better_together:access:docs`. Each row is a decision the owner can approve. A known deviation means the contract records the privacy-forward intent and the app differs. Undecided means the intent is not settled; the app behaviour is pinned.', '',
                 decisions_table, '', '## Affected cells', '']
        contract.decisions.each_key { |id| parts.concat(decision_cells(id)) }
        "#{parts.join("\n")}\n"
      end

      def decisions_table
        header = ['| Decision | Kind | Title | The app does | The privacy rule suggests | Source | Cells |',
                  '| --- | --- | --- | --- | --- | --- | --- |']
        rows = contract.decisions.map do |id, d|
          "| #{id} | #{d['kind'].tr('_',
                                    ' ')} | #{d['title']} | #{d['app_does']} | #{d['privacy_rule']} | #{d['source']} | #{decision_cells_for(id).size} |"
        end
        (header + rows).join("\n")
      end

      def decision_cells_for(id)
        contract.cells.values.select { |c| c.deviation&.dig('decision') == id || c.undecided&.dig('decision') == id }
      end

      def decision_cells(id)
        cells = decision_cells_for(id)
        grouped = cells.group_by { |c| [c.resource, c.action, intended_text(c), actual_text(c)] }.sort_by { |k, _| k.map(&:to_s) }
        lines = grouped.map do |(resource, action, intended, actual), group|
          "- `#{resource}.#{action}`: #{group.map(&:persona).uniq.sort.join(', ')} on #{group.map(&:state).uniq.sort.join(', ')}. #{intended}; app: #{actual}."
        end
        ["### #{id}: #{contract.decisions[id]['title']}", '', *lines, '']
      end

      def intended_text(cell)
        cell.outcome == 'undecided' ? "privacy rule suggests #{cell.undecided['suggests']}" : "contract intends #{cell.outcome}"
      end

      def actual_text(cell)
        cell.undecided ? cell.undecided['actual'] : cell.deviation['actual']
      end

      # ----------------------------------------------- role by permission

      def permission_page
        <<~MD
          # Role by permission matrix

          Generated by `rake better_together:access:docs`. Rows are the permissions the pilot resources check. Columns are the seeded roles. "Checked in" lists the policy files that name the permission.

          #{permission_table}

          Permissions marked opt-in are seeded but held by no default role; they are granted to a custom role on purpose.
        MD
      end

      def permission_table
        roles = seed_roles
        perms = pilot_permissions
        header = ["| Permission | #{roles.join(' | ')} | Checked in | Used by |", "| --- | #{roles.map { '---' }.join(' | ')} | --- | --- |"]
        rows = perms.map { |perm, users| permission_row(perm, users, roles) }
        (header + rows).join("\n")
      end

      def permission_row(perm, users, roles)
        held = roles.map { |role| role_permissions[role]&.include?(perm) ? 'yes' : '-' }
        any = held.include?('yes')
        label = any ? "`#{perm}`" : "`#{perm}` (opt-in)"
        checked = checked_files(perm).map { |f| "`#{f}`" }.join(', ')
        "| #{label} | #{held.join(' | ')} | #{checked} | #{users.sort.map { |u| "`#{u}`" }.join(', ')} |"
      end

      def pilot_permissions
        contract.resources.each_with_object(Hash.new { |h, k| h[k] = [] }) do |(key, res), acc|
          (res['permissions'] || []).each { |perm| acc[perm] << key }
        end.sort.to_h
      end

      def seed_roles
        @seed_roles ||= role_permissions.keys.select do |r|
          r.start_with?('community_') || %w[platform_steward platform_manager platform_member].include?(r)
        end
                                        .select { |r| role_permissions[r].any? { |p| pilot_permissions.key?(p) } || r.start_with?('platform') }
      end

      def role_permissions
        @role_permissions ||= begin
          dir = AccessContract.root.join('config/seeds/better_together/rbac/records')
          rows = YAML.safe_load_file(dir.join('role_resource_permissions.yml'))['records']
          rows.each_with_object(Hash.new { |h, k| h[k] = [] }) do |r, acc|
            acc[r['refs']['role'].split(':').last] << r['refs']['resource_permission'].split(':').last
          end.sort.to_h
        end
      end

      def checked_files(perm)
        Dir[AccessContract.root.join('app/policies/**/*.rb')].select { |f| File.read(f).match?(/['"]#{perm}['"]|:#{perm}\b/) }
                                                             .map { |f| File.basename(f) }.sort
      end

      # ------------------------------------------------------------ heatmaps

      def heat_value(persona, classification, public_rows, source)
        values = contract.cells.values.filter_map do |cell|
          next unless cell.persona == persona && HEAT_ACTIONS.include?(cell.action)
          next unless contract.resources[cell.resource]['classification'] == classification
          next unless (cell.state == 'public') == public_rows

          outcome_for(cell, source)
        end.reject { |v| %w[na pending].include?(v) }
        summarize(values)
      end

      def outcome_for(cell, source)
        return @actual[cell.key] || 'na' if source == :actual

        case cell.outcome
        when 'conditional' then cell.fixture
        when 'undecided' then cell.undecided['suggests']
        else cell.outcome
        end
      end

      def summarize(values)
        return 'n/a' if values.empty?
        return values.first if values.uniq.one?

        'mixed'
      end

      def heat_columns
        used = contract.resources.values.map { |r| r['classification'] }.uniq.sort
        used.flat_map do |klass|
          [[klass, true], [klass, false]].select do |k, pub|
            contract.cells.values.any? do |c|
              contract.resources[c.resource]['classification'] == k && (c.state == 'public') == pub && HEAT_ACTIONS.include?(c.action)
            end
          end
        end
      end

      def heat_label(klass, public_rows)
        "#{klass} #{public_rows ? 'public rows' : 'non-public rows'}"
      end

      def heatmap_table(source)
        cols = heat_columns
        header = ["| Persona | #{cols.map { |k, p| heat_label(k, p) }.join(' | ')} |", "| --- | #{cols.map { '---' }.join(' | ')} |"]
        rows = contract.personas.keys.map do |persona|
          cells = cols.map { |k, p| contract.personas[persona]['status'] == 'pending' ? 'pending' : heat_value(persona, k, p, source) }
          "| `#{persona}` | #{cells.join(' | ')} |"
        end
        (header + rows).join("\n")
      end

      def heatmap_source(source)
        cols = heat_columns
        lines = ['---', "title: #{source == :intended ? 'Intended' : 'Actual'} access by persona and data classification", '---', 'block-beta',
                 "  columns #{cols.size + 1}", '  corner[" "]']
        cols.each_with_index { |(k, p), i| lines << "  h#{i}[\"#{heat_label(k, p)}\"]" }
        classes = []
        contract.personas.each_key.with_index do |persona, r|
          lines << "  p#{r}[\"#{persona}\"]"
          cols.each_with_index do |(k, p), i|
            value = contract.personas[persona]['status'] == 'pending' ? 'pending' : heat_value(persona, k, p, source)
            lines << "  c#{r}_#{i}[\"#{value}\"]"
            classes << "  class c#{r}_#{i} heat_#{value.tr('/', '')}"
          end
        end
        "#{(lines + heat_styles + classes).join("\n")}\n"
      end

      def heat_styles
        ['  classDef heat_allow fill:#cfe8cf,stroke:#2e6b2e,color:#111', '  classDef heat_deny fill:#f3d0d0,stroke:#8a2a2a,color:#111',
         '  classDef heat_mixed fill:#f6e7b4,stroke:#8a6d1a,color:#111', '  classDef heat_na fill:#eeeeee,stroke:#999,color:#333',
         '  classDef heat_pending fill:#eeeeee,stroke:#999,color:#777']
      end

      # ------------------------------------------------------- decision tree

      def tree_source(_key, res)
        action = tree_action(res)
        rules = res['rules'].select { |r| r['applies_to'].nil? || r['applies_to'].include?(action) || r['id'] == 'default_deny' }
        lines = ['---', "title: #{res['title']} #{action} decision tree (generated from the access contract)", '---', 'flowchart TD',
                 "  start([\"#{action} #{res['title'].downcase}\"])"]
        rules.each_with_index { |rule, i| lines.concat(tree_rule_lines(rules, rule, i)) }
        "#{(lines + tree_styles).join("\n")}\n"
      end

      def tree_rule_lines(_rules, rule, index)
        id = "r#{index}"
        prev = index.zero? ? 'start' : "r#{index - 1}"
        lines = []
        lines << "  #{prev} #{index.zero? ? '-->' : '-- no -->'} #{id}"
        label = tree_label(rule)
        lines << (rule['id'] == 'default_deny' ? "  #{id}[\"#{label}\"]" : "  #{id}{\"#{label}\"}")
        lines << "  #{id} -- yes --> #{id}o([\"#{rule['on_yes']}\"])" unless rule['id'] == 'default_deny'
        lines << "  #{id} --> #{id}o([\"deny\"])" if rule['id'] == 'default_deny'
        lines << "  class #{id}o out_#{rule['on_yes']}"
        lines << "  class #{id} unintended" if rule['intended'] == false
        lines
      end

      def tree_label(rule)
        text = rule['question'].to_s.delete('"').gsub(/[(){}\[\]]/, '')
        rule['intended'] == false ? "#{rule['id']}: #{text} (app only)" : "#{rule['id']}: #{text}"
      end

      def tree_styles
        ['  classDef out_allow fill:#cfe8cf,stroke:#2e6b2e,color:#111', '  classDef out_deny fill:#f3d0d0,stroke:#8a2a2a,color:#111',
         '  classDef out_conditional fill:#f6e7b4,stroke:#8a6d1a,color:#111',
         '  classDef unintended stroke:#b00020,stroke-width:3px,stroke-dasharray:6 3,fill:#fde8ea,color:#111']
      end
    end
  end
end
